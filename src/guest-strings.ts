export const GUEST_STRINGS: Record<'en' | 'es' | 'pt', GuestStrings> = { en, es, pt };

// The guest's words for `locale` (`pt-BR` reads as `pt`), English for a language Academy does not speak.
export function guestTranslator(locale: string): (key: keyof GuestStrings, values?: Record<string, string | number>) => string {
  const language = locale.toLowerCase().split('-')[0] as keyof typeof GUEST_STRINGS;
  const words = GUEST_STRINGS[language] ?? en;
  return (key, values = {}) => words[key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}
